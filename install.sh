#!/usr/bin/env bash
# User-level setup for abhay. Never needs sudo.
set -euo pipefail
[[ $EUID -ne 0 ]] || { echo "run as abhay, not root"; exit 1; }

REPO="$(cd "$(dirname "$0")" && pwd)"
UNIT_DIR="$HOME/.config/systemd/user"
QUADLET_DIR="$HOME/.config/containers/systemd"

# Preflight
for cmd in podman rclone fusermount3; do
  command -v "$cmd" >/dev/null || { echo "missing: $cmd"; exit 1; }
done
[[ -f "$HOME/.config/rclone/rclone.conf" ]] || { echo "missing rclone.conf"; exit 1; }
[[ -f "$HOME/.ssh/homelab" ]] || { echo "missing storage box key"; exit 1; }

# Data dirs for Jellyfin
mkdir -p "$REPO/jellyfin/data/config" "$REPO/jellyfin/data/cache"

# Link units from the repo (repo is source of truth)
mkdir -p "$UNIT_DIR" "$QUADLET_DIR"
ln -sfn "$REPO/rclone/rclone-homelab.service" "$UNIT_DIR/rclone-homelab.service"
ln -sfn "$REPO/quadlet/jellyfin.container" "$QUADLET_DIR/jellyfin.container"

systemctl --user daemon-reload
systemctl --user enable --now rclone-homelab.service

for _ in $(seq 1 15); do mountpoint -q /mnt/homelab && break; sleep 1; done
mountpoint -q /mnt/homelab || { echo "mount failed: systemctl --user status rclone-homelab"; exit 1; }

# Jellyfin is generated by Quadlet, so it is started, not enabled
systemctl --user start jellyfin.service

echo "user services up. Check: curl -I https://jellyfin.iamabhay.fyi"
